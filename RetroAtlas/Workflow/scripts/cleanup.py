"""Clean pipeline intermediates only after all requested final products exist."""
from pathlib import Path


def cleanup_run(outpath, samples, sample_names, comparisons, reports, clean_all=False,
                atlas_private=None, atlas_public=None, generated=(), protected_inputs=(),
                final_outputs=()):
    root = Path(outpath).absolute()
    keep = {Path(p).absolute() for p in [*reports, *final_outputs]}
    if not keep or not all(p.is_file() and (p.stat().st_size or p.suffix == '.bed') for p in keep):
        raise ValueError('Cleanup requires every final product to exist (nonempty except a locus-free BED)')
    # Never unlink original alignments, references, panels or their indexes,
    # including when users deliberately put them inside the results directory.
    protected = {Path(row[k]).resolve() for row in samples.values() for k in ('PATH', 'REF')}
    protected.update(Path(p).resolve() for p in protected_inputs if p)
    protected |= {Path(str(p) + suffix) for p in list(protected)
                  for suffix in ('.bai', '.csi', '.crai', '.fai', '.gzi')}
    protected |= {p.with_suffix(suffix) for p in list(protected) for suffix in ('.bai', '.csi', '.crai')}
    removed = []

    def remove(path):
        path = Path(path).absolute()
        if not path.is_relative_to(root) or path == root or path in keep:
            return
        # Do not follow symlinked parents into another result set or input tree.
        if any(p.is_symlink() for p in [path, *path.parents] if p.is_relative_to(root)):
            return
        if path.resolve() in protected:
            return
        if path.is_dir():
            for child in path.iterdir():
                remove(child)
            if not any(path.iterdir()):
                path.rmdir()
        elif path.is_file():
            path.unlink()
            removed.append(str(path))

    for sid in sample_names:
        if samples[sid]['FILE'].upper() == 'CRAM':
            bam = root / sid / 'BAM' / (sid + '.bam')
            for p in (bam, Path(str(bam)+'.bai'), Path(str(bam)+'.csi'), bam.with_suffix('.bai'), bam.with_suffix('.csi')):
                remove(p)
        if clean_all:
            for name in ('BAM', 'HitSV', 'Depth', 'VariantCalling', 'RepeatMasker', 'Event_Reconstruction', 'Reference', 'Report', 'logs'):
                remove(root / sid / name)
    if clean_all:
        # These subdirectories are exclusively generated by this workflow.
        for cid in comparisons:
            for name in ('Inputs', 'Megadepth', 'VariantCalling', 'Evidence', 'logs'):
                remove(root / cid / name)
            remove(root / cid / 'resolved_compare.json')
        for folder in (atlas_private, atlas_public):
            if folder:
                remove(folder)
        # Declared files cover comparison audits/RDS and shared workflow logs.
        owned = [root / name for name in [*sample_names, *comparisons, 'logs']]
        owned += [Path(p).absolute() for p in (atlas_private, atlas_public) if p]
        for path in generated:
            if any(Path(path).absolute().is_relative_to(p) for p in owned):
                remove(path)
    print(f'RetroAtlas cleanup: removed {len(removed)} generated files; retained {len(keep)} final products.')
    return removed
